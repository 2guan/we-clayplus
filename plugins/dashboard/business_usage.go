func usageExamples(name, description string, examples ...string) control.PluginCommandHelp {
	return control.PluginCommandHelp{Name: name, Description: description, Examples: examples}
}

func businessUsage(id string) *control.PluginUsage {
	if _, ok := toolbox.Find(id); !ok {
		return nil
	}
	u := &control.PluginUsage{Commands: businessUsageExamples(id), Steps: []string{
		"先启用插件并检查配置。默认黑名单，空名单对全部会话生效；填入会话 ID 可排除对应对象，切换白名单后仅允许名单内对象。",
	}}
	u.Steps = append(u.Steps, businessUsageDetails[id]...)
	if d, ok := playroom.Find(id); ok {
		if d.GroupOnly {
			u.Steps = append(u.Steps, "本玩法只支持群聊。开局、抽取群内容等触发默认必须先在微信选择真实 @ 本人，再发送标签文字；复制标签或手写 @ 昵称不能创建真实提醒；可在插件配置关闭群聊 @ 要求。")
		} else if id != "romance" && id != "radio" {
			u.Steps = append(u.Steps, "支持私聊；在群聊发起时，默认需要先通过微信真实 @ 本人再发送触发词，可在插件配置关闭。开局后的有效游戏指令无需每次 @。")
		}
		if d.Secret {
			u.Steps = append(u.Steps, "群内先加入，再加本人为微信好友，私聊确认入局。收到收件验证码后回复确认收件，完成双向确认；所有玩家确认后由房主开始。示例中的 abcd1234、123456 分别为演示对局码和验证码，使用时替换为本局实际值。秘密身份和操作只走已确认的好友私聊。")
		}
		if id != "fortune" && id != "group_digest" && id != "group_memes" {
			u.Steps = append(u.Steps, "同一会话只能有一个活动互动局，与海龟汤互斥。进度、怎么玩可查看当前规则；暂停游戏、继续游戏、结束游戏由房主操作，也可在工作台管理。")
		}
		u.Steps = append(u.Steps, "需要模型时，沿用模型中心的流水线与故障切换，全部失败后完整再试一轮；可为此插件指定模型。失败回合在工作台重试，发送结果未知时先核对微信，不能盲目重发。公开游戏会进入普通上下文并带游戏标记，秘密内容不进入普通聊天，均不作为长期记忆。")
	} else if id == "turtlesoup" {
		u.Steps = append(u.Steps, "模型沿用模型中心流水线，失败后选同主题、未玩过的固定题；无对应题目会明确失败。工作台可暂停、结束和重试失败回合，未知发送先核对微信。公开问答带游戏标记进入普通上下文，不作为长期记忆。")
	} else {
		if len(u.Commands) > 0 {
			u.Steps = append(u.Steps, "聊天命令从会话中的文字或引用回复正文触发。群聊默认须真实 @ 本人，可在插件配置关闭；私聊不要求 @。关键词与参数之间一般用空格；网页工作台可选会话、预览结果后单独发送，并查看执行记录。冷却时间和名单仍独立生效。脱机演示不连接真实微信或外部服务。")
		} else {
			u.Steps = append(u.Steps, "通过网页配置或真实系统事件触发，不支持用聊天口令模拟事件。工作台可查看设置与执行记录；脱机演示不会操作真实微信。")
		}
	}
	return u
}

