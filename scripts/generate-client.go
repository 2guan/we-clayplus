//go:build ignore

// 从 SDK Ability 接口生成具有运行周期保护的客户端适配器。
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	root := flag.String("root", ".", "仓库根目录")
	flag.Parse()
	packages := []string{"message", "contact", "chatroom", "moments", "cdn", "favor", "label", "login", "miniapp", "official", "payment", "report", "user"}
	field := func(p string) string {
		if p == "cdn" {
			return "CDN"
		}
		return strings.ToUpper(p[:1]) + p[1:]
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by scripts/generate-client.go; DO NOT EDIT.\n\npackage gateway\n\nimport (\n\"context\"\n\"io\"")
	for _, p := range packages {
		fmt.Fprintf(&out, "sdk%s %q\n", p, "github.com/we-clay/we-clay/sdk/"+p)
	}
	fmt.Fprintln(&out, ")\n\n// Client 提供本次 Run 的业务能力，由 OnReady/OnMessage/OnEvent 传入。\n// 能力字段只读；请保留并复用该对象，不要自行构造。Run 结束后自动失效。\n// 接口覆盖 SDK 已有领域，不代表所有底层操作均已实现或真机验证。\ntype Client struct {\nstate *clientState")
	for _, p := range packages {
		fmt.Fprintf(&out, "%s %s.Ability\n", field(p), "sdk"+p)
	}
	fmt.Fprintln(&out, "}\n\nfunc newClient(ctx context.Context) *Client {\ns := &clientState{ctx: ctx}\nreturn &Client{state:s,")
	for _, p := range packages {
		fmt.Fprintf(&out, "%s: scoped%s{state:s, impl:%s.Instance},\n", field(p), field(p), "sdk"+p)
	}
	fmt.Fprintln(&out, "}}")
	for _, p := range packages {
		f, err := parser.ParseFile(token.NewFileSet(), filepath.Join(*root, "sdk", p, "ability.go"), nil, 0)
		must(err)
		var methods *ast.FieldList
		ast.Inspect(f, func(n ast.Node) bool {
			if t, ok := n.(*ast.TypeSpec); ok && t.Name.Name == "Ability" {
				methods = t.Type.(*ast.InterfaceType).Methods
				return false
			}
			return true
		})
		if methods == nil {
			panic("missing Ability: " + p)
		}
		fmt.Fprintf(&out, "\ntype scoped%s struct { state *clientState; impl %s.Ability }\nvar _ %s.Ability = scoped%s{}\n", field(p), "sdk"+p, "sdk"+p, field(p))
		for _, m := range methods.List {
			ft := m.Type.(*ast.FuncType)
			var params, args, results []string
			for _, a := range ft.Params.List {
				for _, n := range a.Names {
					params = append(params, n.Name+" "+typeName(a.Type, p))
					args = append(args, n.Name)
				}
			}
			for _, r := range ft.Results.List {
				results = append(results, typeName(r.Type, p))
			}
			name := m.Names[0].Name
			result := strings.Join(results, ", ")
			helper := "clientCall"
			if len(results) == 1 {
				if results[0] == "error" {
					helper = "clientDo"
				} else {
					helper = "clientRead"
				}
			} else {
				result = "(" + result + ")"
			}
			fmt.Fprintf(&out, "func (c scoped%s) %s(%s) %s {\nreturn %s(c.state, %q, func() %s {return c.impl.%s(%s)})\n}\n", field(p), name, strings.Join(params, ", "), result, helper, p+"."+name, result, name, strings.Join(args, ", "))
		}
	}
	data, err := format.Source(out.Bytes())
	must(err)
	must(os.WriteFile(filepath.Join(*root, "gateway", "client_abilities.gen.go"), data, 0644))
}

func typeName(e ast.Expr, p string) string {
	switch t := e.(type) {
	case *ast.Ident:
		if ast.IsExported(t.Name) {
			return "sdk" + p + "." + t.Name
		}
		return t.Name
	case *ast.StarExpr:
		return "*" + typeName(t.X, p)
	case *ast.ArrayType:
		if t.Len != nil {
			panic("array unsupported")
		}
		return "[]" + typeName(t.Elt, p)
	case *ast.SelectorExpr:
		return t.X.(*ast.Ident).Name + "." + t.Sel.Name
	default:
		panic(fmt.Sprintf("unsupported type %T", e))
	}
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}
